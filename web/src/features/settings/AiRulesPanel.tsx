import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query';
import { Sparkles, SquarePlus, Trash2 } from 'lucide-react';
import { useState } from 'react';
import { useTranslation } from 'react-i18next';

import { Button } from '../../components/Button';
import { ConfirmDialog } from '../../components/Dialog';
import { Switch } from '../../components/Switch';
import { useToasts } from '../../components/toastContext';
import { ApiError } from '../../lib/api';
import { adminErrorText, INPUT } from './adminUi';
import {
  createRule,
  deleteRule,
  fetchRules,
  previewRule,
  rulesKey,
  testRule,
  toggleRule,
  type AiRuleOut,
  type RuleTestOut,
  type StructuredRule,
} from './settingsApi';

/**
 * W12-17e Pravidlá (admin, Phase 2e): Slovak sentence → AI preview of the „Ak … tak …“ form (text generated by the
 * server from the structure) → optional try on the last 50 e-mails → Uložiť. Saved rules run without AI.
 */
export function AiRulesPanel() {
  const { t } = useTranslation();
  const toasts = useToasts();
  const queryClient = useQueryClient();
  const rules = useQuery({ queryKey: rulesKey, queryFn: fetchRules });
  const [composing, setComposing] = useState(false);
  const [nl, setNl] = useState('');
  const [preview, setPreview] = useState<{ structured: StructuredRule; description: string } | null>(null);
  const [tried, setTried] = useState<RuleTestOut | null>(null);
  const [hint, setHint] = useState<string | null>(null);
  const [deleting, setDeleting] = useState<AiRuleOut | null>(null);
  const refresh = () => void queryClient.invalidateQueries({ queryKey: rulesKey });

  const reset = () => {
    setComposing(false);
    setNl('');
    setPreview(null);
    setTried(null);
    setHint(null);
  };

  const convert = useMutation({
    mutationFn: () => previewRule(nl.trim()),
    onMutate: () => {
      setHint(null);
      setPreview(null);
      setTried(null);
    },
    onSuccess: (out) => setPreview(out),
    onError: (error) =>
      setHint(
        error instanceof ApiError && error.detail.code === 'rule_not_understood'
          ? t('ai.admin.rules.notUnderstood')
          : adminErrorText(t, error),
      ),
  });
  const trial = useMutation({
    mutationFn: () => (preview ? testRule(preview.structured) : Promise.reject(new Error('no preview'))),
    onSuccess: (out) => setTried(out),
    onError: (error) => toasts.error(adminErrorText(t, error)),
  });
  const save = useMutation({
    mutationFn: () => (preview ? createRule(nl.trim(), preview.structured) : Promise.reject(new Error('no preview'))),
    onSuccess: () => {
      reset();
      refresh();
      toasts.success(t('ai.admin.saved'));
    },
    onError: (error) => toasts.error(adminErrorText(t, error)),
  });
  const toggle = useMutation({
    mutationFn: ({ id, enabled }: { id: string; enabled: boolean }) => toggleRule(id, enabled),
    onSuccess: refresh,
    onError: (error) => toasts.error(adminErrorText(t, error)),
  });
  const remove = useMutation({
    mutationFn: (id: string) => deleteRule(id),
    onSuccess: () => {
      setDeleting(null);
      refresh();
    },
    onError: (error) => toasts.error(adminErrorText(t, error)),
  });

  return (
    <section
      className="flex max-w-[var(--layout-settings-form-max)] flex-col gap-4"
      aria-labelledby="ai-rules-title"
      data-testid="settings-ai-rules"
    >
      <div className="flex items-center justify-between gap-2">
        {/* the page title already says „Pravidlá“; keep the name for the region and table */}
        <h2 id="ai-rules-title" className="sr-only">
          {t('ai.admin.rules.title')}
        </h2>
        <span />
        {composing ? null : (
          <Button
            type="button"
            variant="secondary"
            icon={<SquarePlus size={16} aria-hidden="true" />}
            onClick={() => setComposing(true)}
          >
            {t('ai.admin.rules.new')}
          </Button>
        )}
      </div>
      <p className="type-small text-text-secondary">{t('ai.admin.rules.help')}</p>

      {composing ? (
        <div className="flex flex-col gap-3 rounded-md border border-border-default p-4">
          <label className="flex flex-col gap-1">
            <span className="type-label text-text-secondary">{t('ai.admin.rules.nlLabel')}</span>
            <textarea
              value={nl}
              onChange={(e) => {
                setNl(e.target.value);
                setPreview(null);
                setTried(null);
              }}
              rows={3}
              maxLength={1000}
              placeholder={t('ai.admin.rules.nlPlaceholder')}
              className={`${INPUT} h-auto py-2`}
            />
          </label>
          <div className="flex gap-2">
            <Button
              type="button"
              icon={<Sparkles size={16} aria-hidden="true" />}
              disabled={nl.trim().length < 3 || convert.isPending}
              onClick={() => convert.mutate()}
            >
              {t('ai.admin.rules.preview')}
            </Button>
            <Button type="button" variant="secondary" onClick={reset}>
              {t('ai.admin.rules.cancel')}
            </Button>
          </div>
          {hint ? (
            <p role="alert" className="type-small text-danger-600">
              {hint}
            </p>
          ) : null}
          {preview ? (
            <div
              className="flex flex-col gap-2 rounded-md border border-ai-600 bg-ai-50 p-3"
              data-testid="rule-preview"
            >
              <span className="type-label text-text-secondary">{t('ai.admin.rules.previewTitle')}</span>
              <p className="type-body-strong text-text-primary">{preview.description}</p>
              <div className="flex flex-wrap gap-2">
                <Button type="button" variant="secondary" disabled={trial.isPending} onClick={() => trial.mutate()}>
                  {t('ai.admin.rules.try')}
                </Button>
                <Button type="button" disabled={save.isPending} onClick={() => save.mutate()}>
                  {t('ai.admin.rules.save')}
                </Button>
              </div>
              {tried ? (
                <div className="type-small text-text-primary">
                  <p>{t('ai.admin.rules.tried', { count: tried.matches.length, checked: tried.checked })}</p>
                  <ul className="ml-4 list-disc">
                    {tried.matches.slice(0, 10).map((m) => (
                      <li key={m.id}>
                        {m.subject ?? '—'} · {m.from_email ?? ''}
                      </li>
                    ))}
                  </ul>
                </div>
              ) : null}
            </div>
          ) : null}
        </div>
      ) : null}

      {rules.data && rules.data.length === 0 ? (
        <p className="type-small text-text-secondary">{t('ai.admin.rules.empty')}</p>
      ) : (
        <div className="overflow-x-auto" tabIndex={0} role="region" aria-labelledby="ai-rules-title">
          <table className="type-small w-full text-left">
            <thead className="text-text-secondary">
              <tr className="border-b border-border-default">
                <th className="py-2 pr-3 font-semibold">{t('ai.admin.rules.cols.rule')}</th>
                <th className="py-2 pr-3 font-semibold">{t('ai.admin.rules.cols.form')}</th>
                <th className="py-2 pr-3 font-semibold">{t('ai.admin.rules.cols.enabled')}</th>
                <th className="py-2 pr-3 font-semibold">{t('ai.admin.rules.cols.author')}</th>
                <th className="py-2 pr-3 font-semibold">{t('ai.admin.rules.cols.lastUsed')}</th>
                <th className="py-2" aria-label={t('ai.admin.rules.delete')} />
              </tr>
            </thead>
            <tbody>
              {(rules.data ?? []).map((rule) => (
                <tr key={rule.id} className="border-b border-border-default align-top text-text-primary">
                  <td className="py-2 pr-3">{rule.nl_text}</td>
                  <td className="py-2 pr-3">{rule.description}</td>
                  <td className="py-2 pr-3">
                    <Switch
                      checked={rule.enabled}
                      disabled={toggle.isPending}
                      onChange={(enabled) => toggle.mutate({ id: rule.id, enabled })}
                      label={<span className="sr-only">{t('ai.admin.rules.cols.enabled')}</span>}
                    />
                  </td>
                  <td className="py-2 pr-3">{rule.created_by ?? '—'}</td>
                  <td className="py-2 pr-3">
                    {rule.last_used_at
                      ? new Date(rule.last_used_at).toLocaleString('sk-SK')
                      : t('ai.admin.rules.never')}
                  </td>
                  <td className="py-2 text-right">
                    <button
                      type="button"
                      className="rounded-sm p-1.5 text-danger-600 hover:bg-bg-muted"
                      aria-label={`${t('ai.admin.rules.delete')}: ${rule.nl_text}`}
                      onClick={() => setDeleting(rule)}
                    >
                      <Trash2 size={16} aria-hidden="true" />
                    </button>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}

      {deleting ? (
        <ConfirmDialog
          title={t('ai.admin.rules.deleteTitle')}
          body={t('ai.admin.rules.deleteBody')}
          confirmLabel={t('ai.admin.rules.delete')}
          busy={remove.isPending}
          onConfirm={() => remove.mutate(deleting.id)}
          onClose={() => setDeleting(null)}
        />
      ) : null}
    </section>
  );
}
