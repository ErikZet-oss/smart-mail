"""17e Pravidlá in natural language (Phase 2e, #110): the confirmed structured form and its deterministic execution.

The LLM only translates the Slovak sentence into `StructuredRule` for the preview; the person confirms the „Ak … tak …“
text that *code* generates from the structure, and from then on the rule runs without any model (AI_ASSISTANT §2 step
3: rules before classify). Actions are internal only — no send, no move, no Money (autonomy hard rules)."""

from __future__ import annotations

from dataclasses import dataclass
from typing import Literal

from pydantic import BaseModel, Field, field_validator

from app.ai.categories import CATEGORY_BY_ID, CATEGORY_IDS

Field_ = Literal["from_email", "from_domain", "subject", "body", "attachment_name", "has_attachment"]
Op = Literal["contains", "equals", "ends_with"]
ActionType = Literal["set_category", "set_priority", "needs_reply", "no_reply"]

_FIELD_SK = {
    "from_email": "odosielateľ",
    "from_domain": "doména odosielateľa",
    "subject": "predmet",
    "body": "text správy",
    "attachment_name": "názov prílohy",
    "has_attachment": "správa má prílohu",
}
_OP_SK = {"contains": "obsahuje", "equals": "je", "ends_with": "končí na"}
_PRIORITY_SK = {"urgent": "urgentná", "normal": "normálna", "low": "nízka"}


class Condition(BaseModel):
    field: Field_
    op: Op = "contains"
    value: str = Field(default="", max_length=200)

    @field_validator("value")
    @classmethod
    def _value(cls, value: str) -> str:
        return value.strip()


class Action(BaseModel):
    type: ActionType
    value: str | None = None


class StructuredRule(BaseModel):
    match: Literal["all", "any"] = "all"
    conditions: list[Condition] = Field(min_length=1, max_length=5)
    actions: list[Action] = Field(min_length=1, max_length=3)

    @field_validator("conditions")
    @classmethod
    def _conditions(cls, value: list[Condition]) -> list[Condition]:
        for c in value:
            if c.field != "has_attachment" and not c.value:
                raise ValueError("condition needs a value")
        return value

    @field_validator("actions")
    @classmethod
    def _actions(cls, value: list[Action]) -> list[Action]:
        for a in value:
            if a.type == "set_category" and a.value not in CATEGORY_IDS:
                raise ValueError("unknown category")
            if a.type == "set_priority" and a.value not in _PRIORITY_SK:
                raise ValueError("unknown priority")
        types = [a.type for a in value]
        if "needs_reply" in types and "no_reply" in types:
            raise ValueError("needs_reply and no_reply together")
        return value


@dataclass(frozen=True, slots=True)
class MailFacts:
    from_email: str
    subject: str
    body: str
    attachment_names: tuple[str, ...]


def _matches(c: Condition, mail: MailFacts) -> bool:
    if c.field == "has_attachment":
        return bool(mail.attachment_names)
    needle = c.value.casefold()
    if c.field == "attachment_name":
        values = [n.casefold() for n in mail.attachment_names]
    elif c.field == "from_domain":
        values = [mail.from_email.rsplit("@", 1)[-1].casefold()] if "@" in mail.from_email else []
    else:
        values = [getattr(mail, c.field).casefold()]
    if c.op == "equals":
        return any(v == needle for v in values)
    if c.op == "ends_with":
        return any(v.endswith(needle) for v in values)
    return any(needle in v for v in values)


def rule_matches(rule: StructuredRule, mail: MailFacts) -> bool:
    hits = (_matches(c, mail) for c in rule.conditions)
    return all(hits) if rule.match == "all" else any(hits)


def describe(rule: StructuredRule) -> str:
    """The „Ak … tak …“ sentence shown for confirmation — generated by code, never by the model."""
    joiner = " a " if rule.match == "all" else " alebo "
    conds = joiner.join(
        _FIELD_SK[c.field] if c.field == "has_attachment" else f"{_FIELD_SK[c.field]} {_OP_SK[c.op]} „{c.value}“"
        for c in rule.conditions
    )
    acts = []
    for a in rule.actions:
        if a.type == "set_category":
            acts.append(f"kategória = {CATEGORY_BY_ID[a.value or ''].label_sk}")
        elif a.type == "set_priority":
            acts.append(f"priorita = {_PRIORITY_SK[a.value or '']}")
        elif a.type == "needs_reply":
            acts.append("treba odpovedať")
        else:
            acts.append("netreba odpovedať (AI nepripraví odpoveď)")
    return f"Ak {conds}, tak {', '.join(acts)}."


@dataclass(frozen=True, slots=True)
class RuleOutcome:
    rule_id: str
    category: str | None
    priority: str | None
    needs_reply: bool | None


def outcome_of(rule_id: str, rule: StructuredRule) -> RuleOutcome:
    category = next((a.value for a in rule.actions if a.type == "set_category"), None)
    priority = next((a.value for a in rule.actions if a.type == "set_priority"), None)
    types = {a.type for a in rule.actions}
    needs = True if "needs_reply" in types else False if "no_reply" in types else None
    return RuleOutcome(rule_id=rule_id, category=category, priority=priority, needs_reply=needs)


def first_match(rules: list[tuple[str, StructuredRule]], mail: MailFacts) -> RuleOutcome | None:
    """First enabled rule that matches (rules are ordered by creation, oldest first)."""
    for rule_id, rule in rules:
        if rule_matches(rule, mail):
            return outcome_of(rule_id, rule)
    return None
